function catalogDishesForSample(
  kitchenKey: string,
  brandName: string,
  outletName: string,
  isVerified: boolean,
  score: number | null,
): DiscoveryDishMatchDto[] {
  const catalog = SAMPLE_CATALOG_BY_KITCHEN_KEY[kitchenKey];
  if (!catalog) {
    return [];
  }
  return catalog.items
    .filter((item) => item.isAvailable)
    .map((item) => ({
      itemId: item.itemId,
      outletId: kitchenKey,
      restaurantId: catalog.restaurantId,
      brandName,
      outletName,
      categoryId: item.categoryId,
      title: item.title,
      description: item.description,
      pricePaise: item.pricePaise,
      formattedPriceInr: formatInrFromPaise(item.pricePaise),
      dietaryType: item.dietaryType,
      dietaryBadgeLabel: DIETARY_LABELS[item.dietaryType],
      allergens: [...item.allergens],
      allergenLabels: [...item.allergenLabels],
      isAvailable: item.isAvailable,
      outletVerifiedClean: isVerified,
      outletSafetyScore: score,
    }));
}

